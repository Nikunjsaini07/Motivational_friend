function pickVerified(kind, session) {
  const category = kind === 'distraction' ? 'attention' : 'study';
  const bank = MF_VERIFIED_QUOTES.filter(q => q.category === category);
  const recent = session.usedQuotes.classics || [];
  const pool = bank.filter(q => !recent.includes(q.id));
  const choices = pool.length ? pool : bank;
  const quote = choices[Math.floor(Math.random() * choices.length)];
  session.usedQuotes.classics = [...recent, quote.id].slice(-6);
  return quote;
}
